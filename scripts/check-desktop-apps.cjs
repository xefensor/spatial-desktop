const assert=require('node:assert/strict'),fs=require('node:fs');
const Apps=require('../dist/desktop-apps.js');
assert.equal(Apps.calculate('(12 + 8) × 1.21'),24.2);
assert.equal(Apps.calculate('2 + 3 * 4'),14);
assert.equal(Apps.calculate('(-4 + 2) / -2'),1);
assert.equal(Apps.calculate('250 * 15%'),37.5);
assert.equal(Apps.calculate('.1 + .2'),.3);
assert.equal(Apps.calculate('1e3 / 4'),250);
for(const expression of ['1/0','globalThis.alert(1)','1;2','2 ** 3','(1+2','1..2','Infinity','9e999'])assert.throws(()=>Apps.calculate(expression),undefined,expression);
assert.throws(()=>Apps.calculate('('.repeat(60)+'1'+')'.repeat(60)));
assert.deepEqual(Apps.cropBounds({x:120,y:80},{x:20,y:15},100,60),{x:20,y:15,width:80,height:45});
assert.deepEqual(Apps.cropBounds({x:-10,y:-8},{x:25,y:35},100,60),{x:0,y:0,width:25,height:35});
assert.equal(Apps.appFor('Spectacle'),'screenshot');assert.equal(Apps.appFor('Discover'),'software');assert.equal(Apps.appFor('Krita'),null);
for(const info of Object.values(Apps.definitions))assert.equal(info.singleInstance,true);
const source=fs.readFileSync(require.resolve('../dist/desktop-apps.js'),'utf8');
assert.match(source,/getDisplayMedia\(\{video:true,audio:false/,'Capture requires the browser sharing chooser');
assert.match(source,/stream\.getTracks\(\)\.forEach\(track=>track\.stop\(\)\);await setImage/,'Sharing stops before encoding and saving');
assert.match(source,/saveBlob\(/,'Images save through the ordinary persistent file API');
assert.doesNotMatch(source,/eval\(|new Function\(|foreignObject|html2canvas/);
console.log('Desktop apps: safe calculations, crop bounds, honest catalog routing, and capture/save lifecycle passed.');
