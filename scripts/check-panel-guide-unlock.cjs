'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const G = require('../dist/spatial-guide.js');

// A real Guide progression and the native Quick launch module run against the
// bounded panel renderer. No full desktop boot or unrelated service is needed.
const fixture = fs.readFileSync(path.join(__dirname, 'check-panel-desktop.cjs'), 'utf8');
const marker = fixture.indexOf("test('runtime-only fixture");
assert(marker >= 0);
const harness = {require, process, console, __dirname, module: {exports: {}}};
vm.runInNewContext(fixture.slice(0, marker) + '\nmodule.exports={w,d,context,P,registry};', harness, {filename: 'panel-guide-unlock-fixture.cjs'});
const {w, d, context, P, registry} = harness.module.exports;
const model = G.create({status: 'active', mode: 'first', version: 9, index: 0, done: []});
w.SpatialGuide.model = model;
w.SpatialGuide.applyGate = () => {};
w.SpatialGuide.panelWidgetAllowed = id => id === 'launcher' || model.allows(G.panelFeature(id));
const apps = registry.get('apps').source;
apps.querySelector('#appsQuickLaunch').remove();
const rack = d.createElement('nav'); rack.id = 'appRack'; apps.querySelector('.apps-scroll-region').append(rack);
w.workspaceProfiles.general.favorites = [['notes', 'Notes']];
w.prepareControlSemantics = () => {};
w.desktopNavigationBlocked = () => false;
let launches = 0;
w.createAppInstance = () => {launches++;};
vm.runInContext(fs.readFileSync(path.join(__dirname, '../dist/apps-quick-launch.js'), 'utf8'), context, {filename: 'apps-quick-launch.js'});
for (const [id, tag] of [['universalSearchInput', 'input'], ['overviewProjectZoneTitle', 'h2']]) {const node = d.createElement(tag); node.id = id; d.body.append(node);}
w.$ = (selector, root = d) => root.querySelector(selector);
w.filterLauncher = () => {};
w.preparePanelLesson = () => {};
const desktop = fs.readFileSync(path.join(__dirname, '../dist/guide-desktop.js'), 'utf8');
const start = desktop.indexOf('  function updateGate() {');
assert(start >= 0);
const update = desktop.slice(start, desktop.indexOf('\n  function guideProseMarkup(', start));
vm.runInContext('const guide=SpatialGuide,model=guide.model;\n' + update, context, {filename: 'guide-gate-transition.js'});
const updateGate = () => vm.runInContext('updateGate()', context);
const native = () => apps.querySelector('#appsQuickLaunch [data-quick-launch-app="notes"]');
const compact = () => d.querySelector('.panel-compact-pins [data-panel-launch="notes"]');
const compactClock = () => d.querySelector('.panel-compact-clock');
const nativeClock = registry.get('clock').source;
P.updatePanel('panel-left', {mode: 'compact'}); updateGate();
assert(native().disabled && compact().disabled, 'First-run Welcome blocks both launcher presentations');
assert(compactClock().disabled); assert.equal(nativeClock.getAttribute('aria-disabled'), 'true');
const saved = JSON.stringify(P.state());
assert(model.next()); assert.equal(model.lesson.id, 'system'); updateGate();
assert(native().disabled && compact().disabled, 'System lesson still gates Apps');
assert.equal(compactClock().disabled, false); assert.equal(nativeClock.getAttribute('aria-disabled'), 'false', 'Clock directly follows the current System gate');
for (const goal of model.lesson.goals) model.mark(goal);
assert(model.next()); assert.equal(model.lesson.id, 'apps'); updateGate();
assert.equal(native().disabled, false, 'Next refreshes the native launcher without an incidental window sync');
assert.equal(compact().disabled, false, 'The compact view receives the refreshed native enabled state in the same transition');
assert.equal(JSON.stringify(P.state()), saved, 'Guide gate refreshes do not edit the saved panel layout');
compact().click(); assert.equal(launches, 1, 'The newly unlocked compact launcher invokes the real shared command');
P.updatePanel('panel-left', {mode: 'expanded'}); native().click();
assert.equal(launches, 2, 'The newly unlocked expanded launcher invokes that same command');
model.state.index = 0; updateGate();
assert(native().disabled && compact().disabled, 'Returning to a gated lesson disables both projections again');
assert(compactClock().disabled); assert.equal(nativeClock.getAttribute('aria-disabled'), 'true');
w.close();
console.log('Panel Guide unlock passed: first-run Next updates native and compact launchers, shared launch actions and Clock gating without editing saved layouts.');
